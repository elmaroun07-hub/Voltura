import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { catalog } from "./catalog";

/**
 * Article 50(1), EU AI Act (6b): the person must be told they are talking to
 * an AI. The Assistant is named as one, and the notice is on screen before the
 * first answer, in both languages.
 */
const NOTICE = {
  es: "Las respuestas las genera un modelo de IA y pueden contener errores.",
  en: "Answers are generated by an AI model and may contain errors.",
} as const;

const NAME = { es: "Asistente de IA", en: "AI Assistant" } as const;

const src = (rel: string) => readFileSync(new URL(rel, import.meta.url), "utf8");

describe.each(["es", "en"] as const)("Article 50(1) disclosure, %s", (lang) => {
  it("names the Assistant as an AI in the nav and the page title", () => {
    expect(catalog[lang]["nav.assistant"]).toBe(NAME[lang]);
  });

  it("carries the exact notice text", () => {
    expect(catalog[lang]["chat.aiNotice"]).toBe(NOTICE[lang]);
  });

  it("no longer calls the Assistant an energy assistant", () => {
    expect(catalog[lang]["nav.assistant"]).not.toMatch(/energ/i);
    expect(catalog[lang]["chat.conversationTitle"]).not.toMatch(/energ/i);
    expect(catalog[lang]["chat.conversationTitle"]).toMatch(lang === "es" ? /Asistente de IA/ : /AI Assistant/);
  });
});

describe("where the notice and the name are rendered", () => {
  const chat = src("../components/chat/ChatInterface.tsx");

  it("the notice sits above the message list, so it is on screen before the first answer", () => {
    const notice = chat.indexOf('t("chat.aiNotice")');
    expect(notice).toBeGreaterThan(-1);
    expect(notice).toBeLessThan(chat.indexOf("messages.map"));
    expect(notice).toBeLessThan(chat.indexOf('t("chat.hello")'));
  });

  it("the nav entry and the page heading both use the renamed label", () => {
    expect(src("../components/layout/Shell.tsx")).toContain('label: "nav.assistant"');
    expect(src("../pages/Assistant.tsx")).toContain('t("nav.assistant")');
  });
});
